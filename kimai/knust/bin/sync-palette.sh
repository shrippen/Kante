#!/usr/bin/env bash
# Copies Knust's palette from Kante into Resources/public/css/knust-palette.css (vendored, never edited here).
#
#   Kante tokens/palette.json ──► kante/tools/build-knust.py ──► docs/v1/knust-palette.css
#                                                                   │  (https://shrippen.github.io/v1/knust-palette.css)
#                                                                   ▼
#                                                  bin/sync-palette.sh ──► Resources/public/css/knust-palette.css
#
# Usage: bin/sync-palette.sh [<kante checkout>]
#   with a path (or KANTE_DIR): copies <kante>/docs/v1/knust-palette.css (run Kante's ./build.sh first)
#   without: downloads the published file
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
URL="https://shrippen.github.io/v1/knust-palette.css"
TARGET="$ROOT/Resources/public/css/knust-palette.css"
KANTE="${1:-${KANTE_DIR:-}}"

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

# Source: a Kante checkout if given, else the published copy
if [ -n "$KANTE" ]; then
    cp "$KANTE/docs/v1/knust-palette.css" "$tmp"
    from="$KANTE/docs/v1/knust-palette.css"
else
    curl -fsSL "$URL" -o "$tmp"
    from="$URL"
fi

# Only a generated palette is taken: it names its generator in the header
if ! grep -q 'generated by kante/tools/build-knust.py' "$tmp"; then
    echo "Error: $from is not Kante's generated Knust palette" >&2
    exit 1
fi

if cmp -s "$tmp" "$TARGET"; then
    echo "knust-palette.css already matches $from"
    exit 0
fi
cp "$tmp" "$TARGET"
echo "updated Resources/public/css/knust-palette.css from $from"
